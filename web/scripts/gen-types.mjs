// Generates src/schema/bundle.ts from schema/bundle.schema.json, the JSON Schema that
// `python -m system1_doom.export --schema` dumps from the pydantic models.
import { readFile, writeFile } from 'node:fs/promises'
import { compile } from 'json-schema-to-typescript'

const here = new URL('..', import.meta.url)
const schema = JSON.parse(await readFile(new URL('schema/bundle.schema.json', here), 'utf8'))

// Pydantic titles every property; json-schema-to-typescript would turn each title into its own alias.
// Keep titles only on the named models in $defs so the output reads as one interface per model.
function dropPropertyTitles(node, keep) {
  if (Array.isArray(node)) return node.forEach((child) => dropPropertyTitles(child, false))
  if (node === null || typeof node !== 'object') return
  if (!keep) delete node.title
  for (const [key, child] of Object.entries(node)) {
    // $defs and properties are maps keyed by name (a property may itself be called "title").
    if (key === '$defs') Object.values(child).forEach((def) => dropPropertyTitles(def, true))
    else if (key === 'properties') Object.values(child).forEach((prop) => dropPropertyTitles(prop, false))
    else dropPropertyTitles(child, false)
  }
}
dropPropertyTitles(schema, true)
const banner = `/* Generated by scripts/gen-types.mjs from schema/bundle.schema.json. Do not edit by hand:
 * run \`npm run schema && npm run types\` after changing the Python trace models. */`
const ts = await compile(schema, 'Bundle', {
  bannerComment: banner,
  unreachableDefinitions: true,
  additionalProperties: false,
  style: { singleQuote: true, semi: false, printWidth: 120 },
})
await writeFile(new URL('src/schema/bundle.ts', here), ts)
console.log('Wrote src/schema/bundle.ts')
